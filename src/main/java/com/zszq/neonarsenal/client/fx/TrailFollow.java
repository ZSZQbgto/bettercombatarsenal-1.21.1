package com.zszq.neonarsenal.client.fx;

import java.util.ArrayList;
import java.util.Iterator;
import java.util.List;

import com.zszq.neonarsenal.mixin.ParticleAccessor;

import net.minecraft.client.particle.Particle;
import net.minecraft.client.player.AbstractClientPlayer;

/**
 * Makes <b>Better Combat's slash trail</b> follow the attacking player instead of staying where it
 * was spawned in the world.
 *
 * <p>Better Combat spawns its slash trail (the "刀光") as particles at the attack position, so while
 * a player moves fast (mounted, elytra gliding, ...) the trail hangs in the air relative to the
 * ground. During a Better Combat trail spawn this class records only the particles created by
 * Better Combat itself (class package {@code net.bettercombat}) together with their caster, and every
 * client tick shifts those particles (world and previous position) by the caster's movement since the
 * last tick. The trail therefore stays attached to the player while it fades out.</p>
 *
 * <p>Particles generated by this mod (sparks, block burst, ...) and any other particles are never
 * touched: only Better Combat's own trail particles are tracked.</p>
 */
public final class TrailFollow {

    private static final String BETTER_COMBAT_PACKAGE = "net.bettercombat.";

    private static final class Tracked {
        private final Particle particle;
        private final AbstractClientPlayer caster;
        private double lastX;
        private double lastY;
        private double lastZ;

        private Tracked(Particle particle, AbstractClientPlayer caster) {
            this.particle = particle;
            this.caster = caster;
            this.lastX = caster.getX();
            this.lastY = caster.getY();
            this.lastZ = caster.getZ();
        }
    }

    private static final List<Tracked> TRACKED = new ArrayList<>();
    private static AbstractClientPlayer caster;
    private static long casterSince;

    private TrailFollow() {
    }

    /** Called when Better Combat starts spawning a slash trail. */
    public static void begin(AbstractClientPlayer player) {
        caster = player;
        casterSince = System.nanoTime();
    }

    /** Called when the trail spawn finished. */
    public static void end() {
        caster = null;
    }

    /** {@return true while Better Combat is spawning a trail}. */
    public static boolean isSpawning() {
        if (caster != null && System.nanoTime() - casterSince > 1_000_000_000L) {
            // Safety: the spawn call threw or was interrupted; stop tracking new particles.
            caster = null;
        }
        return caster != null;
    }

    /** Records one Better Combat trail particle so it can be dragged along with its caster. */
    public static void track(Particle particle) {
        if (caster == null || particle == null) {
            return;
        }
        if (!particle.getClass().getName().startsWith(BETTER_COMBAT_PACKAGE)) {
            // Never touch this mod's own particles (or any non-Better-Combat particle).
            return;
        }
        TRACKED.add(new Tracked(particle, caster));
    }

    /** Drops all tracked particles and the current caster (used on disconnect). */
    public static void clear() {
        TRACKED.clear();
        caster = null;
    }

    /** Called every client tick: moves all live trail particles by their caster's tick movement. */
    public static void tick() {
        if (TRACKED.isEmpty()) {
            return;
        }
        Iterator<Tracked> iterator = TRACKED.iterator();
        while (iterator.hasNext()) {
            Tracked tracked = iterator.next();
            if (!tracked.particle.isAlive() || tracked.caster.isRemoved()
                    || tracked.caster.level() == null) {
                iterator.remove();
                continue;
            }
            double x = tracked.caster.getX();
            double y = tracked.caster.getY();
            double z = tracked.caster.getZ();
            double dx = x - tracked.lastX;
            double dy = y - tracked.lastY;
            double dz = z - tracked.lastZ;
            if (dx * dx + dy * dy + dz * dz > 1.0E-8D) {
                ParticleAccessor accessor = (ParticleAccessor) tracked.particle;
                accessor.neonarsenal$setX(accessor.neonarsenal$x() + dx);
                accessor.neonarsenal$setY(accessor.neonarsenal$y() + dy);
                accessor.neonarsenal$setZ(accessor.neonarsenal$z() + dz);
                accessor.neonarsenal$setPreviousX(accessor.neonarsenal$previousX() + dx);
                accessor.neonarsenal$setPreviousY(accessor.neonarsenal$previousY() + dy);
                accessor.neonarsenal$setPreviousZ(accessor.neonarsenal$previousZ() + dz);
            }
            tracked.lastX = x;
            tracked.lastY = y;
            tracked.lastZ = z;
        }
    }
}
